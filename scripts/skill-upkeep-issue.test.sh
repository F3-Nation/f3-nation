#!/usr/bin/env bash
# Regression tests for scripts/skill-upkeep-issue.sh, run against a throwaway
# git repository whose skill folders have known commit dates.
# Run directly: bash scripts/skill-upkeep-issue.test.sh
set -uo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
generator="${script_dir}/skill-upkeep-issue.sh"
failures=0

if ! command -v git >/dev/null 2>&1; then
  echo "FAIL: git is required to run these tests"
  exit 1
fi

pass() { echo "PASS: $1"; }
fail() {
  echo "FAIL: $1"
  if [[ -n "${2:-}" ]]; then
    printf '%s\n' "$2" | sed 's/^/    /'
  fi
  failures=$((failures + 1))
}

assert_contains() {
  local description="$1" needle="$2" haystack="$3"
  if [[ "$haystack" == *"$needle"* ]]; then pass "$description"; else fail "$description" "$haystack"; fi
}

assert_not_contains() {
  local description="$1" needle="$2" haystack="$3"
  if [[ "$haystack" != *"$needle"* ]]; then pass "$description"; else fail "$description" "$haystack"; fi
}

tmp_dir=""
trap 'if [[ -n "$tmp_dir" ]]; then rm -rf "$tmp_dir"; fi' EXIT
tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/skill-upkeep-test.XXXXXX")" || exit 1
repo="$tmp_dir/repo"
mkdir -p "$repo"

git_at() {
  local date="$1"
  shift
  GIT_AUTHOR_DATE="${date}T12:00:00Z" GIT_COMMITTER_DATE="${date}T12:00:00Z" \
    git -C "$repo" -c user.name=test -c user.email=test@example.invalid "$@"
}

commit_skill() {
  local name="$1" date="$2"
  mkdir -p "$repo/.agents/skills/$name"
  echo "# $name" >"$repo/.agents/skills/$name/SKILL.md"
  git -C "$repo" add -A
  git_at "$date" commit -q -m "add $name"
}

git -C "$repo" init -q
commit_skill zeta 2026-01-05
commit_skill alpha 2026-03-01
commit_skill pr-review-inline 2026-02-10
mkdir -p "$repo/.agents/skills/pr-review-inline/benchmark"
echo "# bench" >"$repo/.agents/skills/pr-review-inline/benchmark/README.md"
git -C "$repo" add -A
git_at 2026-04-20 commit -q -m "add benchmark"
# A folder without SKILL.md is not a skill.
mkdir -p "$repo/.agents/skills/notes"
echo "x" >"$repo/.agents/skills/notes/README.md"
git -C "$repo" add -A
git_at 2026-04-21 commit -q -m "add notes"
# A skill that exists only in the working tree has no commit date.
mkdir -p "$repo/.agents/skills/draft"
echo "# draft" >"$repo/.agents/skills/draft/SKILL.md"

run() { (cd "$repo" && env -u GITHUB_REPOSITORY bash "$generator" "$@" 2>&1); }

out="$(run)"
status=$?
if [[ $status -eq 0 ]]; then pass "exits 0 for a valid skills folder"; else fail "exits 0 (got $status)" "$out"; fi

assert_contains "starts with the hidden marker" "<!-- skill-upkeep-reminder -->" "$(printf '%s\n' "$out" | head -1)"
assert_not_contains "skips folders without SKILL.md" "notes" "$out"
assert_contains "dates a skill by its folder's last commit" "\`pr-review-inline\`](https://github.com/F3-Nation/f3-nation/blob/main/.agents/skills/pr-review-inline/SKILL.md) (last changed 2026-04-20)" "$out"
assert_contains "labels an uncommitted skill" "\`draft\`](https://github.com/F3-Nation/f3-nation/blob/main/.agents/skills/draft/SKILL.md) (not committed yet)" "$out"
assert_contains "asks pr-review-inline for the benchmark" "(last changed 2026-04-20): run the [benchmark](https://github.com/F3-Nation/f3-nation/blob/main/.agents/skills/pr-review-inline/benchmark/README.md)" "$out"
assert_contains "asks other skills for one real run" "(last changed 2026-01-05): run it once and fix anything stale" "$out"
assert_contains "ends by asking for the issue to be closed" "close this issue" "$(printf '%s\n' "$out" | tail -3)"
assert_contains "says the workflow generated it" "_Generated by the [skill upkeep reminder workflow]" "$(printf '%s\n' "$out" | tail -1)"

order="$(printf '%s\n' "$out" | sed -n 's/^- \[ \] \[`\([^`]*\)`.*/\1/p' | tr '\n' ' ')"
if [[ "$order" == "draft zeta alpha pr-review-inline " ]]; then
  pass "lists skills oldest first"
else
  fail "lists skills oldest first (got: $order)"
fi

out="$(run --repo fork/repo --ref dev)"
assert_contains "--repo and --ref set the links" "https://github.com/fork/repo/blob/dev/.agents/skills/alpha/SKILL.md" "$out"

out="$(cd "$repo" && GITHUB_REPOSITORY=env/repo bash "$generator" 2>&1)"
assert_contains "GITHUB_REPOSITORY sets the default repo" "https://github.com/env/repo/blob/main/" "$out"

rm "$repo/.agents/skills/pr-review-inline/benchmark/README.md"
out="$(run)"
assert_contains "falls back to one real run without a benchmark" "(last changed 2026-04-20): run it once and fix anything stale" "$out"

expect_failure() {
  local description="$1" expected_status="$2"
  shift 2
  local output status
  output="$(run "$@")"
  status=$?
  if [[ $status -eq $expected_status ]]; then pass "$description"; else fail "$description (exit $status)" "$output"; fi
}

expect_failure "rejects a malformed --repo" 2 --repo "not a repo"
expect_failure "rejects a flag with no value" 2 --ref
expect_failure "rejects an unknown argument" 2 --bogus
expect_failure "fails when the skills folder is missing" 1 --skills-dir nowhere
mkdir -p "$repo/empty"
expect_failure "fails when no skill is found" 1 --skills-dir empty

if [[ $failures -gt 0 ]]; then
  echo "${failures} test(s) failed"
  exit 1
fi
echo "All skill-upkeep-issue tests passed"
