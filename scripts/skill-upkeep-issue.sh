#!/usr/bin/env bash
# Prints the Markdown body of the monthly agent-skill upkeep issue that
# .github/workflows/skill-upkeep-reminder.yml keeps open. Each directory under
# the skills folder with a SKILL.md becomes one task, oldest last commit first,
# so the skills most likely to have drifted from the code are checked first.
#
# Usage: bash scripts/skill-upkeep-issue.sh [--repo OWNER/NAME] [--ref REF] [--skills-dir DIR]
#   --repo        repository the issue's links point at (default: $GITHUB_REPOSITORY,
#                 else F3-Nation/f3-nation)
#   --ref         branch the links point at (default: main)
#   --skills-dir  skills folder, relative to the repository root
#                 (default: .agents/skills)
#
# Dates come from git history, so the checkout needs full history; a shallow
# clone reports every skill as last changed on the clone's one commit.
set -euo pipefail

# The workflow finds its open issue by this line, so changing it orphans the
# issue that is already open and the next run opens a second one.
readonly MARKER='<!-- skill-upkeep-reminder -->'
readonly BENCHMARKED_SKILL='pr-review-inline'

repo="${GITHUB_REPOSITORY:-F3-Nation/f3-nation}"
ref="main"
skills_dir=".agents/skills"

usage() {
  echo "Usage: bash scripts/skill-upkeep-issue.sh [--repo OWNER/NAME] [--ref REF] [--skills-dir DIR]" >&2
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo | --ref | --skills-dir)
      if [[ $# -lt 2 || -z "$2" ]]; then
        echo "error: $1 needs a value" >&2
        usage
        exit 2
      fi
      case "$1" in
        --repo) repo="$2" ;;
        --ref) ref="$2" ;;
        --skills-dir) skills_dir="${2%/}" ;;
      esac
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "error: unknown argument: $1" >&2
      usage
      exit 2
      ;;
  esac
done

if [[ ! "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
  echo "error: --repo must look like OWNER/NAME, got: $repo" >&2
  exit 2
fi

repo_root="$(git rev-parse --show-toplevel)"
cd "$repo_root"

if [[ ! -d "$skills_dir" ]]; then
  echo "error: skills folder not found: $skills_dir" >&2
  exit 1
fi

blob_url="https://github.com/${repo}/blob/${ref}"
tree_url="https://github.com/${repo}/tree/${ref}"

# One "<date> <name>" line per skill. A skill with no commit yet sorts first
# under "0000-00-00" and prints as "not committed yet".
rows=""
for skill_md in "$skills_dir"/*/SKILL.md; do
  [[ -f "$skill_md" ]] || continue
  dir="${skill_md%/SKILL.md}"
  name="${dir##*/}"
  date="$(git log -1 --format=%cs -- "$dir")"
  rows+="${date:-0000-00-00} ${name}"$'\n'
done

if [[ -z "$rows" ]]; then
  echo "error: no SKILL.md found under $skills_dir" >&2
  exit 1
fi

benchmark_path="${skills_dir}/${BENCHMARKED_SKILL}/benchmark/README.md"

cat <<EOF
${MARKER}
Agent skills are the runbooks AI assistants follow in this repository, kept in [\`${skills_dir}\`](${tree_url}/${skills_dir}). They go stale quietly: the code, the tools or the AI model change, and nothing fails until a run goes wrong. This issue is the monthly reminder to check them.

**What to do:** pick a skill below, check it, and tick its box. Anyone can help; a codeowner signs off. Skills are listed by the date of their last commit, oldest first, since those are the most likely to be out of date.

- **\`${BENCHMARKED_SKILL}\`**: a codeowner runs [its review benchmark](${blob_url}/${benchmark_path}) on the AI model codeowners use for reviews right now and pastes the results table into a comment here, with the agent tool, model and skill commit. If a finding the benchmark expects is missed, open an issue for it.
- **Every other skill:** run it once for real, on the kind of task it is for. Fix anything that is wrong or out of date in a pull request, and note what you checked in a comment here.

EOF

while read -r date name; do
  [[ -n "$name" ]] || continue
  if [[ "$date" == "0000-00-00" ]]; then
    when="not committed yet"
  else
    when="last changed ${date}"
  fi
  link="[\`${name}\`](${blob_url}/${skills_dir}/${name}/SKILL.md)"
  if [[ "$name" == "$BENCHMARKED_SKILL" && -f "$benchmark_path" ]]; then
    echo "- [ ] ${link} (${when}): run the [benchmark](${blob_url}/${benchmark_path}) and paste the results table"
  else
    echo "- [ ] ${link} (${when}): run it once and fix anything stale"
  fi
done < <(printf '%s' "$rows" | LC_ALL=C sort)

cat <<EOF

When this month's checks are done, close this issue. Next month's run opens a new one; a run while this one is still open updates this list instead.

_Generated by the [skill upkeep reminder workflow](${blob_url}/.github/workflows/skill-upkeep-reminder.yml)._
EOF
