-- Requires an approved target, owner session, stopped writers and fresh backup.
-- Run with psql -X -v ON_ERROR_STOP=1 -f ...; defaults to ROLLBACK.
BEGIN;
SET LOCAL statement_timeout = '10s';
SET LOCAL lock_timeout = '3s';
SET LOCAL idle_in_transaction_session_timeout = '60s';
SET LOCAL search_path = pg_catalog, pg_temp;
LOCK TABLE codex.user_submissions IN ACCESS EXCLUSIVE MODE;

DO $$
BEGIN
  IF (SELECT relkind <> 'r' OR relrowsecurity FROM pg_class
      WHERE oid = 'codex.user_submissions'::regclass)
     OR EXISTS (SELECT FROM pg_inherits WHERE inhrelid = 'codex.user_submissions'::regclass
                OR inhparent = 'codex.user_submissions'::regclass) THEN
    RAISE EXCEPTION 'Unsupported partition, inheritance or row security';
  END IF;
  IF EXISTS (SELECT FROM pg_constraint WHERE
      (conrelid = 'codex.user_submissions'::regclass AND contype IN ('p','f'))
      OR (confrelid = 'codex.user_submissions'::regclass AND contype = 'f'))
     OR EXISTS (SELECT FROM pg_trigger WHERE tgrelid = 'codex.user_submissions'::regclass AND NOT tgisinternal)
     OR EXISTS (SELECT FROM pg_rewrite WHERE ev_class = 'codex.user_submissions'::regclass) THEN
    RAISE EXCEPTION 'Existing key, foreign key, trigger or rule requires fresh review';
  END IF;
  IF NOT EXISTS (SELECT FROM pg_attribute WHERE attrelid = 'codex.user_submissions'::regclass
      AND attname = 'id' AND atttypid = 'integer'::regtype AND attidentity = 'a' AND attnotnull)
     OR pg_get_serial_sequence('codex.user_submissions','id') IS DISTINCT FROM 'codex.user_submissions_id_seq'
     OR NOT EXISTS (SELECT FROM pg_sequence WHERE seqrelid = 'codex.user_submissions_id_seq'::regclass
                    AND seqincrement = 1 AND NOT seqcycle AND seqcache = 1) THEN
    RAISE EXCEPTION 'Unexpected identity configuration';
  END IF;
END $$;

-- A new private schema deliberately makes a second execution fail closed.
CREATE SCHEMA pr825_submission_repair;
REVOKE ALL ON SCHEMA pr825_submission_repair FROM PUBLIC;
CREATE TABLE pr825_submission_repair.id_map (
  new_id integer PRIMARY KEY,
  old_id integer NOT NULL,
  original_row_md5 text NOT NULL
);
REVOKE ALL ON TABLE pr825_submission_repair.id_map FROM PUBLIC;

-- Snapshot and physical tuple IDs exist only in this locked transaction.
-- Earliest creation wins; tied dates use timestamp then ctid. This is an
-- operational choice, not a claim about which record historically owned an ID.
CREATE TEMP TABLE submission_before ON COMMIT DROP AS
SELECT ctid AS tuple_id, id AS old_id, to_jsonb(s) AS original,
       row_number() OVER (PARTITION BY id ORDER BY created_at, "timestamp", ctid) AS position
FROM codex.user_submissions s;
CREATE TEMP TABLE submission_plan ON COMMIT DROP AS
WITH extras AS (
  SELECT tuple_id, row_number() OVER (ORDER BY old_id, position) AS offset_id
  FROM submission_before WHERE position > 1
), bounds AS (
  SELECT greatest(coalesce(max(old_id), 0), 0)::bigint AS top FROM submission_before
)
SELECT b.*, CASE WHEN e.tuple_id IS NULL THEN b.old_id::bigint
                ELSE bounds.top + e.offset_id END AS new_id
FROM submission_before b LEFT JOIN extras e USING (tuple_id) CROSS JOIN bounds;

DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM submission_plan WHERE position > 1) THEN
    RAISE EXCEPTION 'No duplicate IDs; nothing to repair';
  END IF;
  IF (SELECT max(new_id) FROM submission_plan) >= 2147483647 THEN
    RAISE EXCEPTION 'Insufficient integer ID capacity including next insert';
  END IF;
END $$;

INSERT INTO pr825_submission_repair.id_map (new_id, old_id, original_row_md5)
SELECT new_id::integer, old_id, md5(original::text) FROM submission_plan;

ALTER TABLE codex.user_submissions ALTER COLUMN id SET GENERATED BY DEFAULT;
UPDATE codex.user_submissions s SET id = p.new_id::integer
FROM submission_plan p WHERE s.ctid = p.tuple_id AND p.new_id <> p.old_id;
ALTER TABLE codex.user_submissions ALTER COLUMN id SET GENERATED ALWAYS;

-- Exact JSON equality proves every other column survived, including NULLs.
DO $$ BEGIN
  IF (SELECT count(*) FROM codex.user_submissions) <> (SELECT count(*) FROM submission_plan)
     OR EXISTS (
       SELECT FROM submission_plan p LEFT JOIN codex.user_submissions s ON s.id = p.new_id
       WHERE s.id IS NULL OR (to_jsonb(s) - 'id') IS DISTINCT FROM (p.original - 'id')
     ) THEN
    RAISE EXCEPTION 'Row preservation check failed';
  END IF;
END $$;
ALTER TABLE codex.user_submissions ADD CONSTRAINT user_submissions_pkey PRIMARY KEY (id);

-- RESTART is transactional; setval is not. Never move an advanced sequence back.
-- Writers and direct sequence consumers must remain stopped throughout.
DO $$
DECLARE next_id bigint;
BEGIN
  SELECT greatest((SELECT max(id)::bigint + 1 FROM codex.user_submissions),
                  last_value + CASE WHEN is_called THEN 1 ELSE 0 END)
  INTO next_id FROM codex.user_submissions_id_seq;
  IF next_id > (SELECT seqmax FROM pg_sequence WHERE seqrelid = 'codex.user_submissions_id_seq'::regclass) THEN
    RAISE EXCEPTION 'Sequence exhausted';
  END IF;
  EXECUTE format('ALTER SEQUENCE codex.user_submissions_id_seq RESTART WITH %s', next_id);
END $$;

SELECT count(*) AS preserved_rows,
       count(*) FILTER (WHERE old_id <> new_id) AS reassigned_rows
FROM pr825_submission_repair.id_map;

-- Replace ONLY after separate approval of the exact production operation.
ROLLBACK;
